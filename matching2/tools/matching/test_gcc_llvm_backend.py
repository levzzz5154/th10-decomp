class ProfileValidationTests(BackendFixture):
    def test_valid_profile_loads_without_invoking_tools(self):
        profile = self.profile()
        self.assertEqual(profile["_path"], self.profile_path)
        self.assertEqual(profile["_pass"], self.pass_path)
        self.assertEqual(profile["kind"], backend.KIND)
        self.assertEqual(self.calls, [])

    def test_unknown_kind_and_unknown_fields_are_rejected(self):
        mutations = [
            lambda p: p.update(kind="gcc-byte-patch"),
            lambda p: p.update(postprocess=["trim"]),
            lambda p: p["tools"]["gcc"].update(version="unpinned"),
            lambda p: p["plugin"].update(binary="cached.so"),
        ]
        original = json.loads(json.dumps(self.profile_data))
        for mutation in mutations:
            with self.subTest(mutation=mutation):
                self.profile_data = json.loads(json.dumps(original))
                mutation(self.profile_data)
                self.write_profile()
                with self.assertRaises(backend.GCCBackendError):
                    self.profile()

    def test_flags_cannot_change_output_or_load_unreviewed_code(self):
        for flags in [["-Oz"], ["-Oz", "-O2", "-ffunction-sections"],
                      ["-Oz", "-ffunction-sections", "-fplugin=other.so"],
                      ["-Oz", "-ffunction-sections", "-o"],
                      ["-Oz", "-ffunction-sections", "-Oz"]]:
            with self.subTest(flags=flags):
                self.profile_data["flags"] = flags
                self.write_profile()
                with self.assertRaisesRegex(backend.GCCBackendError, "reviewed GCC flags"):
                    self.profile()

    def test_schema_bool_and_bad_hash_are_rejected(self):
        self.profile_data["schema_version"] = True
        self.write_profile()
        with self.assertRaisesRegex(backend.GCCBackendError, "schema_version"):
            self.profile()
        self.profile_data["schema_version"] = 1
        self.profile_data["tools"]["gcc"]["sha256"] = "not-a-hash"
        self.write_profile()
        with self.assertRaisesRegex(backend.GCCBackendError, "SHA-256"):
            self.profile()

    def test_profile_and_pass_cannot_escape_project(self):
        outside = self.root / "outside.json"
        outside.write_text(self.profile_path.read_text())
        for name in ["../outside.json", str(outside), "layout/../compilers/gcc.json"]:
            with self.subTest(name=name), self.assertRaises(backend.GCCBackendError):
                backend.load_profile(self.project, name)
        link = project_support(self.project, 'layout/compilers/escape.json')
        link.symlink_to(outside)
        with self.assertRaisesRegex(backend.GCCBackendError, "existing project file"):
            backend.load_profile(self.project, "layout/compilers/escape.json")
        self.profile_data["plugin"]["source"] = "../outside.cc"
        self.write_profile()
        with self.assertRaisesRegex(backend.GCCBackendError, "canonical project-relative"):
            self.profile()


