def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _write_coff(path, body, *, symbol_value=0, relocations=()):
    """Write one function section and one external relocation target."""
    raw_offset = 60
    reloc_offset = raw_offset + len(body)
    symbol_offset = reloc_offset + 10 * len(relocations)
    header = struct.pack("<HHIIIHH", 0x14C, 1, 0, symbol_offset, 2, 0, 0)
    section = struct.pack(
        "<8sIIIIIIHHI", b".text\0\0\0", 0, 0, len(body), raw_offset,
        reloc_offset if relocations else 0, 0, len(relocations), 0, 0x60500020,
    )
    records = b"".join(struct.pack("<IIH", offset, 1, kind)
                       for offset, kind in relocations)
    symbols = (
        struct.pack("<8sIhHBB", b"_body\0\0\0", symbol_value, 1, 0x20, 2, 0)
        + struct.pack("<8sIhHBB", b"_callee\0", 0, 0, 0x20, 2, 0)
    )
    path.write_bytes(header + section + body + records + symbols + struct.pack("<I", 4))


class WholeSectionOwnershipTests(unittest.TestCase):
    def test_padding_is_rejected_instead_of_truncated(self):
        with tempfile.TemporaryDirectory() as directory:
            project = Path(directory)
            source, output = project / "raw.obj", project / "normalized.obj"
            _write_coff(source, b"\x90" * 29 + b"\xc3\x90\x90")
            with self.assertRaisesRegex(CoffRegionError, "extent 32 differs from requested size 30"):
                normalize_object(source, output, [{
                    "symbol": "_body", "address": "0x00401000", "size": 30,
                }])
            self.assertFalse(output.exists())

    def test_whole_bytes_and_relocation_locations_are_preserved(self):
        with tempfile.TemporaryDirectory() as directory:
            project = Path(directory)
            source, output = project / "raw.obj", project / "normalized.obj"
            body = b"\xe8\0\0\0\0\xc3\x90\x90"
            _write_coff(source, body, relocations=[(1, 0x14)])
            report = normalize_object(source, output, [{
                "symbol": "_body", "address": "0x00401000", "size": len(body),
            }])
            normalized = _read_object(output)
            self.assertEqual(normalized["machine"], 0x14C)
            self.assertEqual(normalized["sections"][0]["raw"], body)
            self.assertEqual(normalized["sections"][0]["raw_size"], len(body))
            self.assertEqual(normalized["sections"][0]["relocations"][0]["virtual_address"], 1)
            self.assertEqual(normalized["sections"][0]["relocations"][0]["type"], 0x14)
            selected = report["regions"][0]
            self.assertEqual(selected["sha256"], hashlib.sha256(body).hexdigest())
            self.assertEqual(selected["original_relocations"][0]["symbol"], "_callee")
            self.assertEqual(selected["original_relocations"][0]["virtual_address"], 1)

    def test_nonzero_function_offset_cannot_claim_whole_section(self):
        with tempfile.TemporaryDirectory() as directory:
            project = Path(directory)
            source, output = project / "raw.obj", project / "normalized.obj"
            _write_coff(source, b"\x90\xc3", symbol_value=1)
            with self.assertRaisesRegex(CoffRegionError, "no definition at value 0"):
                normalize_object(source, output, [{
                    "symbol": "_body", "address": "0x00401000", "size": 1,
                }])
            self.assertFalse(output.exists())


class BackendFixture(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.project = self.root / "project"
        self.output = self.root / "output"
        self.source = "src/polar.cpp"
        self.profile_name = "layout/compilers/gcc.json"
        self.source_path = self.project / self.source
        self.profile_path = self.project / self.profile_name
        self.pass_path = self.project / "compiler/initialize.cc"
        self.include_path = self.project / "include/vector.hpp"
        for path, content in [(self.source_path, "// source\n"),
                              (self.pass_path, "// generic pass\n"),
                              (self.include_path, "// header\n")]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        self.sdk = self.root / "sdk"
        self.sdk.mkdir()
        (self.sdk / "gcc-plugin.h").write_text("// SDK\n")
        self.tools = {}
        for name in sorted(backend.TOOLS):
            path = self.root / "tools" / name
            path.parent.mkdir(exist_ok=True)
            path.write_text("mock executable " + name + "\n")
            self.tools[name] = {"path": str(path), "sha256": _sha(path)}
        self.profile_data = {
            "schema_version": 1, "kind": backend.KIND,
            "description": "Reviewed ordinary C++ compiler profile",
            "flags": ["-Oz", "-ffunction-sections", "-mfpmath=387"],
            "tools": self.tools,
            "plugin": {
                "source": "compiler/initialize.cc", "source_sha256": _sha(self.pass_path),
                "sdk": str(self.sdk),
                "sdk_sha256": backend.tree_hash(backend.tree_snapshot(self.sdk)),
            },
        }
        self.write_profile()
        self.config = {
            "source_compilers": {self.source: self.profile_name},
            "regions": [{"source": self.source, "kind": "semantic", "symbol": "_body",
                         "address": "0x00401000", "size": 1}],
        }
        self.calls = []
        self.failure_stage = None
        self.skip_stage_output = None
        self.mutation = None
        self.dependency_extra = None
        self.body = b"\xc3"

    def write_profile(self):
        self.profile_path.parent.mkdir(parents=True, exist_ok=True)
        self.profile_path.write_text(json.dumps(self.profile_data))

    def profile(self):
        return backend.load_profile(self.project, self.profile_name)

    def validate(self, clusters=None):
        return backend.validate_source_compilers(self.project, self.config, clusters)

    def fake_run(self, args, **kwargs):
        args = list(map(str, args))
        self.calls.append((args, kwargs))
        stdout = ""
        if any(arg.startswith("-print-prog-name=") for arg in args):
            requested = next(arg.split("=", 1)[1] for arg in args
                             if arg.startswith("-print-prog-name="))
            host = args[0] == self.tools["host_cxx"]["path"]
            target = ("host_" if host else "") + requested
            stdout = self.tools[target]["path"] + "\n"
            stage = "resolve-" + target
        elif "--version" in args:
            stage = "version"
            stdout = "mock pinned tool version\n"
        elif "-M" in args:
            stage = "host-dependencies" if args[0] == self.tools["host_cxx"]["path"] else "source-dependencies"
        elif "-S" in args:
            stage = "cpp"
        elif "-filetype=obj" in args:
            stage = "assemble"
        else:
            stage = "plugin"
        if self.failure_stage == stage:
            return subprocess.CompletedProcess(args, 1, stdout, "intentional compiler failure\n")
        if stage in ("host-dependencies", "source-dependencies", "plugin", "cpp"):
            if "-MF" in args:
                deps = [self.pass_path, self.sdk / "gcc-plugin.h"] if stage.startswith("host") or stage == "plugin" else [self.source_path, self.include_path]
                if stage in ("source-dependencies", "cpp") and self.dependency_extra:
                    deps.append(self.dependency_extra)
                depfile = Path(args[args.index("-MF") + 1])
                depfile.write_text("target: " + " ".join(map(str, deps)) + "\n")
            if stage in ("plugin", "cpp") and self.skip_stage_output != stage:
                Path(args[args.index("-o") + 1]).write_text(
                    "mock shared plugin\n" if stage == "plugin" else ".text\n_body:\n ret\n"
                )
        if stage == "assemble" and self.skip_stage_output != stage:
            _write_coff(Path(args[args.index("-o") + 1]), self.body)
        if self.mutation:
            self.mutation(stage, args)
        return subprocess.CompletedProcess(args, 0, stdout, "")

    def compile(self):
        profile = self.profile()
        with patch.object(backend.subprocess, "run", side_effect=self.fake_run):
            return backend.compile_gcc_llvm(self.project, self.output, 3, self.source, profile)


